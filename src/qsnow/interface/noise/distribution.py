_REGISTRY: Dict[str, Type["NoiseDistribution"]] = {}

# Generic so a decorated class keeps its own type: annotating the decorator as returning
# `Type[NoiseDistribution]` would make static checkers see every subclass as the base,
# whose constructor is just `(*, seed=None)`.
_D = TypeVar("_D", bound=Type["NoiseDistribution"])


def register_distribution(cls: _D) -> _D:
    """Class decorator: make `cls` reconstructible from a record by its `name`."""
    _REGISTRY[cls.name] = cls
    return cls


def distribution_from_dict(data: Dict[str, Any]) -> "NoiseDistribution":
    """Rebuild a distribution from its `as_dict()` record."""
    name = data.get("name")
    cls = _REGISTRY.get(name)
    if cls is None:
        raise ValueError(
            f"Unknown noise distribution {name!r}; registered: {sorted(_REGISTRY)}."
        )
    return cls(**cls._coerce({k: v for k, v in data.items() if k != "name"}))


def as_profile(value: NoiseProfile | float) -> NoiseProfile:
    """A fresh `NoiseProfile` from a rate or a profile - the one coercion every setter uses.

    Copies the whole profile rather than rebuilding it from `p`, so a field added to
    `NoiseProfile` later is never silently dropped on the way onto a chip.
    """
    return value.copy() if isinstance(value, NoiseProfile) else NoiseProfile(float(value))


def profiles(keys: Iterable, rates: Iterable[float]) -> Dict[Any, NoiseProfile]:
    """One fresh `NoiseProfile` per key; the single place a producer builds its output."""
    return {k: NoiseProfile(float(p)) for k, p in zip(keys, rates)}


def _fresh_seed() -> int:
    return SeedSequence().entropy


@dataclass(repr=False)
class NoiseDistribution(ABC):
    """
    A recipe for a PER landscape: parameters, a seed, and the two producers.

    `seed` is resolved at construction (a fresh one when None and the distribution is
    randomized), so the object always carries the seed it will use and `as_dict()` is a
    complete, replayable record. Equality is by recipe - parameters and seed.
    """

    name: ClassVar[str]
    randomized: ClassVar[bool] = True
    seed: Optional[int] = field(default=None, kw_only=True)

    def __post_init__(self) -> None:
        if self.randomized and self.seed is None:
            self.seed = _fresh_seed()

    def __repr__(self) -> str:
        args = ", ".join(f"{k}={v!r}" for k, v in self.as_dict().items() if k != "name")
        return f"{type(self).__name__}({args})"

    # ------------------------------------------------------------------
    # Recipe
    # ------------------------------------------------------------------
    @property
    def params(self) -> Dict[str, Any]:
        """Every field except `seed`, positional ones first."""
        declared = [f for f in dataclass_fields(self) if f.name != "seed"]
        ordered = [f for f in declared if not f.kw_only] + [f for f in declared if f.kw_only]
        return {f.name: getattr(self, f.name) for f in ordered}

    def as_dict(self) -> Dict[str, Any]:
        """The flat `{name, **params, seed}` record display surfaces and flakes read."""
        flat: Dict[str, Any] = {"name": self.name, **self.params}
        if self.seed is not None:
            flat["seed"] = self.seed
        return flat

    @staticmethod
    def from_dict(data: Dict[str, Any]) -> "NoiseDistribution":
        return distribution_from_dict(data)

    @classmethod
    def _coerce(cls, kwargs: Dict[str, Any]) -> Dict[str, Any]:
        """Hook for subclasses whose fields lose type through JSON (tuples -> lists)."""
        return kwargs

    # ------------------------------------------------------------------
    # Production
    # ------------------------------------------------------------------
    @abstractmethod
    def sites(self, chip: "Chip") -> Dict[Coord, NoiseProfile]:
        """A noise profile for every site of `chip`."""

    @abstractmethod
    def couplers(
        self, chip: "Chip", *, correlation: Optional[float] = None
    ) -> Dict[CouplerKey, NoiseProfile]:
        """A profile for every coupler of `chip`.

        `correlation` ties the coupler landscape to the site landscape the chip currently
        holds; only distributions built on a Gaussian field can honour it.
        """

    def _reject_correlation(self, correlation: Optional[float]) -> None:
        if correlation is not None:
            raise ValueError(
                f"{type(self).__name__} has no Gaussian field, so it cannot be "
                f"cross-correlated with the sites (correlation={correlation})."
            )


