@dataclass(repr=False)
class GaussianFieldDistribution(NoiseDistribution):
    """
    A landscape built in two steps: a Gaussian field that carries only spatial
    structure (`_gaussian_field`), then a reshaping of its values into the requested
    marginal (`_to_rates`). Subclasses fill those two hooks and inherit sites, couplers,
    and the cross-correlated coupler path.

    Couplers read the field at their two endpoints (the field lives on sites). With a
    `correlation` ρ the coupler latent is `ρ·A + √(1−ρ²)·B` - `A` the normal scores of
    the endpoint-mean site rates the chip currently holds, `B` the field's endpoint
    means - so ρ is exactly the correlation between a coupler and its endpoint-mean
    latent (the linear model of coregionalization). ρ = 1 reproduces the ordering
    `derive_coupler_noise("mean")` gives; ρ = 0 ignores the sites entirely.
    """

    @abstractmethod
    def _gaussian_field(self, chip: "Chip") -> Dict[Coord, float]:
        """One Gaussian number per site, carrying only spatial structure."""

    @abstractmethod
    def _to_rates(self, values: np.ndarray) -> np.ndarray:
        """Gaussian numbers -> error rates with the requested marginal, order preserved."""

    def sites(self, chip: "Chip") -> Dict[Coord, NoiseProfile]:
        field_ = self._gaussian_field(chip)
        return profiles(field_.keys(), self._to_rates(np.fromiter(field_.values(), float)))

    def _uncorrelated_couplers(self, chip: "Chip") -> Dict[CouplerKey, NoiseProfile]:
        """Couplers from the field alone; the branch taken when no correlation is asked."""
        field_ = self._gaussian_field(chip)
        couplers = chip.couplers
        own = [mean(field_[e] for e in c.ends) for c in couplers]
        return profiles([c.ends for c in couplers], self._to_rates(np.asarray(own)))

    def couplers(
        self, chip: "Chip", *, correlation: Optional[float] = None
    ) -> Dict[CouplerKey, NoiseProfile]:
        if correlation is None:
            return self._uncorrelated_couplers(chip)
        couplers = chip.couplers
        site_latent = normal_scores(
            [mean(chip.loc(e).noise.p for e in c.ends) for c in couplers]
        )
        field_ = self._gaussian_field(chip)
        own_latent = [mean(field_[e] for e in c.ends) for c in couplers]
        latent = blend_latents(site_latent, own_latent, correlation)
        return profiles([c.ends for c in couplers], self._to_rates(latent))


@dataclass(repr=False)
class _IIDDistribution(GaussianFieldDistribution):
    """
    Shared shape of the two independent-draw distributions.

    Plain output keeps scipy `rvs` draws, one per entry in chip order and rounded to
    five decimals, exactly as the original generators did, so a recorded seed
    reproduces the identical chip. The Gaussian-field path (`_gaussian_field` +
    `_to_rates`) is only taken when a coupler correlation is requested; it draws from
    the same marginal by inverse transform.
    """

    def _target(self):
        raise NotImplementedError

    def _draw(self, n: int) -> list:
        rng = default_rng(self.seed)
        dist = self._target()
        return [round(dist.rvs(1, random_state=rng)[0], 5) for _ in range(n)]

    def sites(self, chip: "Chip") -> Dict[Coord, NoiseProfile]:
        keys = list(chip.noise_map.keys())
        return profiles(keys, self._draw(len(keys)))

    def _uncorrelated_couplers(self, chip: "Chip") -> Dict[CouplerKey, NoiseProfile]:
        keys = list(chip.coupler_map.keys())
        return profiles(keys, self._draw(len(keys)))

    def _gaussian_field(self, chip: "Chip") -> Dict[Coord, float]:
        return iid_gaussian_field(chip, self.seed)

    def _to_rates(self, values: np.ndarray) -> np.ndarray:
        return quantile_map(values, self._target())


@register_distribution
@dataclass(repr=False)
class RandomUniform(_IIDDistribution):
    """Independent draws from a uniform distribution over `bounds = (low, high)`.

    Parameters
    ----------
    bounds : (float, float)
        Lower and upper rate of the interval.
    seed : int, optional (keyword-only)
        RNG seed; a fresh one is drawn and recorded when omitted.
    """

    name: ClassVar[str] = "uniform random"
    bounds: Tuple[float, float]

    @classmethod
    def _coerce(cls, kwargs: Dict[str, Any]) -> Dict[str, Any]:
        if "bounds" in kwargs:
            kwargs = {**kwargs, "bounds": tuple(kwargs["bounds"])}
        return kwargs

    def _target(self):
        low, high = self.bounds
        return uniform(loc=low, scale=high - low)


@register_distribution
@dataclass(repr=False)
class RandomGaussian(_IIDDistribution):
    """Independent draws from a normal distribution truncated to the admissible range.

    Parameters
    ----------
    mean, deviation : float
        Mean and standard deviation of the (untruncated) normal, in rate units.
    seed : int, optional (keyword-only)
        RNG seed; a fresh one is drawn and recorded when omitted.
    """

    name: ClassVar[str] = "gaussian"
    mean: float
    deviation: float

    def _target(self):
        floor, _ = p_bounds()
        return truncnorm(
            (floor - self.mean) / self.deviation,
            (1 - self.mean) / self.deviation,
            loc=self.mean,
            scale=self.deviation,
        )


@dataclass(repr=False)
class ContourDistribution(GaussianFieldDistribution):
    """
    A spatially correlated landscape: the field is white noise box-averaged over a
    distance-`slope` tile footprint, so `slope` is the correlation length in unit cells.
    Subclasses choose the reshape.
    """

    slope: int = field(default=5, kw_only=True)

    @abstractmethod
    def _white_noise(self) -> Tuple[float, float]:
        """`(mean, deviation)` of the white noise the field is averaged from."""

    def _gaussian_field(self, chip: "Chip") -> Dict[Coord, float]:
        mean_, deviation = self._white_noise()
        return correlated_gaussian_field(chip, mean_, deviation, self.seed, self.slope)


@register_distribution
@dataclass(repr=False)
class NormalContour(ContourDistribution):
    """A correlated landscape with a normal marginal - the original contour model.

    Parameters
    ----------
    mean, deviation : float
        Mean and standard deviation of the landscape, in rate units.
    seed : int, optional (keyword-only)
        RNG seed; a fresh one is drawn and recorded when omitted.
    slope : int, keyword-only, default 5
        Correlation length in unit cells (the tile distance of the box filter); >= 3.
    """

    name: ClassVar[str] = "normal contour"
    mean: float
    deviation: float

    def _white_noise(self) -> Tuple[float, float]:
        return self.mean, self.deviation

    def _to_rates(self, values: np.ndarray) -> np.ndarray:
        return scale_gaussian_contour(values, self.deviation)


@register_distribution
@dataclass(repr=False)
class SkewContour(ContourDistribution):
    """
    A correlated landscape with a skewed (Pearson III) marginal.

    `skew > 0` is right-skewed (a long tail of bad qubits), `skew == 0` is normal.
    `location` pins the mean, or the median with `center="median"`. Same seed and slope
    as `NormalContour` give the same peaks and valleys; only the values differ.

    The three parameters are *raw-value* statistics, for synthetic sweeps in rate
    units. Measured calibration data is a bell on a *log* axis; use `LogSkewContour` for
    it. A Pearson III has a floor `2·deviation/skew` below its mean and its mode only
    `(4/skew² − 1)·deviation·skew/2` above that floor, so above `skew ≈ 1.5` the
    landscape is a one-sided decline from the floor rather than a bell.

    Parameters
    ----------
    location : float
        The mean of the landscape (or its median with `center="median"`), in rate units.
    deviation : float
        Standard deviation, in rate units.
    skew : float, default 0.0
        Skewness of the rates; 0 is the normal distribution.
    center : {"mean", "median"}, default "mean"
        Which statistic `location` pins.
    seed : int, optional (keyword-only)
        RNG seed; a fresh one is drawn and recorded when omitted.
    slope : int, keyword-only, default 5
        Correlation length in unit cells; >= 3.
    """

    name: ClassVar[str] = "skewed contour"
    location: float
    deviation: float
    skew: float = 0.0
    center: Center = "mean"

    def _white_noise(self) -> Tuple[float, float]:
        return self.location, self.deviation

    def _to_rates(self, values: np.ndarray) -> np.ndarray:
        return quantile_map(
            values, skewed_target(self.location, self.deviation, self.skew, center=self.center)
        )


@register_distribution
@dataclass(repr=False)
class LogSkewContour(ContourDistribution):
    """
    A correlated landscape whose *logarithm* has a skewed (Pearson III) marginal.

    This is the log-Pearson III ("LP3") distribution, the shape of the working-component
    bulk of calibration data: error rates form a slightly right-skewed bell on a log
    axis. `skew == 0` gives a log-normal landscape. Same seed and slope as the other
    contours give the same peaks and valleys.

    The three parameters are plain sample statistics of that bulk. Calibration data is
    two populations on a log axis - the bell, and a bump of failed components one to
    two decades to the right. Take the values inside Tukey's fences on log10(rate)
    (Q1 − 1.5·IQR to Q3 + 1.5·IQR, the box-plot outlier rule; the calibration histogram
    tool's `--stats log` prints these as its `bulk` line) and pass their median rate,
    the sd of log10(rate) and the skewness of log10(rate). Typical bulk values are
    0.2-0.25 decades and skew 0.2-1. The all-data statistics are not a substitute: the
    failed bump pushes the log skew to 1.5-2, and a Pearson III has its mode only
    `(4/skew² − 1)·deviation·skew/2` decades above its floor, which at those skews is a
    one-sided decline from the floor, not a bell. The landscape then has no failed
    components; a generated chip models the working population only.

    Parameters
    ----------
    location : float
        A rate: the median of the landscape (`center="median"`), or its geometric mean
        `10 ** mean(log10 rate)` (`center="geometric"`).
    deviation : float
        Spread of log10(rate), in decades (its standard deviation); ~0.2-0.25 for the
        bulk of readout and two-qubit errors on recent devices.
    skew : float, default 0.0
        Skewness of log10(rate); 0 is log-normal, ~0.2-1 for the bulk of calibration
        data.
    center : {"median", "geometric"}, default "median"
        Which statistic `location` pins.
    seed : int, optional (keyword-only)
        RNG seed; a fresh one is drawn and recorded when omitted.
    slope : int, keyword-only, default 5
        Correlation length in unit cells; >= 3.
    """

    name: ClassVar[str] = "log skewed contour"
    location: float
    deviation: float
    skew: float = 0.0
    center: LogCenter = "median"

    def _white_noise(self) -> Tuple[float, float]:
        # only the field's structure is used; a plausible scale keeps the buffer's
        # truncated normal well inside its bounds
        return self.location, self.location * self.deviation

    def _to_rates(self, values: np.ndarray) -> np.ndarray:
        return quantile_map(
            values,
            log_skewed_target(self.location, self.deviation, self.skew, center=self.center),
        )
